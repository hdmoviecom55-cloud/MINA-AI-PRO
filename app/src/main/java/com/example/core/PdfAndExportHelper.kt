    fun generatePdf(context: Context, title: String, docType: String, body: String): File {
        val docsDir = File(context.filesDir, "documents").apply { mkdirs() }
        val safeName = title.replace(Regex("[^a-zA-Z0-9_-]"), "_").take(36).ifBlank { "mina_document" }
        val file = File(docsDir, "${safeName}_${System.currentTimeMillis()}.pdf")

        val pageWidth = 595
        val pageHeight = 842
        val margin = 48
        val contentWidth = pageWidth - margin * 2

        val pdf = PdfDocument()
        val titlePaint = Paint().apply {
            color = Color.rgb(34, 22, 14)
            textSize = 20f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }
        val metaPaint = Paint().apply {
            color = Color.rgb(180, 95, 10)
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }
        val linePaint = Paint().apply {
            color = Color.rgb(220, 160, 50)
            strokeWidth = 2f
        }
        val bodyPaint = TextPaint().apply {
            color = Color.rgb(35, 35, 35)
            textSize = 11.5f
            isAntiAlias = true
        }

        val layout = StaticLayout.Builder
            .obtain(body, 0, body.length, bodyPaint, contentWidth)
            .setAlignment(Layout.Alignment.ALIGN_NORMAL)
            .setLineSpacing(4f, 1.15f)
            .build()

        var pageNumber = 1
        var lineIndex = 0
        val totalLines = layout.lineCount

        while (lineIndex < totalLines || pageNumber == 1) {
            val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
            val page = pdf.startPage(pageInfo)
            val canvas = page.canvas

            var yPos = margin.toFloat()
            if (pageNumber == 1) {
                canvas.drawText("MINA AI • $docType", margin.toFloat(), yPos, metaPaint)
                yPos += 24f
                canvas.drawText(title.take(55), margin.toFloat(), yPos, titlePaint)
                yPos += 12f
                canvas.drawLine(margin.toFloat(), yPos, (pageWidth - margin).toFloat(), yPos, linePaint)
                yPos += 22f
            } else {
                canvas.drawText("$title (Page $pageNumber)", margin.toFloat(), yPos, metaPaint)
                yPos += 24f
            }

            val bottomLimit = pageHeight - margin - 18f
            while (lineIndex < totalLines) {
                val lineHeight = layout.getLineBottom(lineIndex) - layout.getLineTop(lineIndex)
                if (yPos + lineHeight > bottomLimit) break
                val start = layout.getLineStart(lineIndex)
                val end = layout.getLineEnd(lineIndex)
                val lineStr = body.substring(start, end).trimEnd('\n', '\r')
                canvas.drawText(lineStr, margin.toFloat(), yPos + 12f, bodyPaint)
                yPos += lineHeight.toFloat()
                lineIndex++
            }

            val footerDate = SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(Date())
            canvas.drawText("Generated by MINA AI • $footerDate", margin.toFloat(), (pageHeight - 24).toFloat(), metaPaint)
            pdf.finishPage(page)
            pageNumber++
            if (totalLines == 0) break
        }

        FileOutputStream(file).use { out ->
            pdf.writeTo(out)
        }
        pdf.close()
        return file
    }

    fun exportUserDataJson(
        context: Context,
        profile: UserProfile,
        memories: List<MemoryItem>,
        journals: List<JournalEntry>,
        documents: List<SavedDocument>,
        places: List<FavoritePlace>
    ): File {
        val exportsDir = File(context.filesDir, "exports").apply { mkdirs() }
        val file = File(exportsDir, "mina_ai_export_${System.currentTimeMillis()}.json")

        val root = JSONObject().apply {
            put("exportedAt", SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).format(Date()))
            put("app", "MINA AI")
            put("profile", JSONObject().apply {
                put("displayName", profile.displayName)
                put("bio", profile.bio)
                put("privateNoteDecrypted", CryptoVault.decrypt(profile.privateNote))
                put("personality", profile.personality)
                put("emotionLevel", profile.emotionLevel)
                put("language", profile.language)
                put("youtubeUrl", profile.youtubeUrl)
                put("instagramUrl", profile.instagramUrl)
                put("socialUrl", profile.socialUrl)
                put("musicUrl", profile.musicUrl)
            })
            put("memories", JSONArray().apply {
                memories.forEach { m ->
                    put(JSONObject().apply {
                        put("title", m.title)
                        put("content", if (m.encrypted) CryptoVault.decrypt(m.content) else m.content)
                        put("category", m.category)
                        put("encrypted", m.encrypted)
                    })
                }
            })
            put("journals", JSONArray().apply {
                journals.forEach { j ->
                    put(JSONObject().apply {
                        put("title", j.title)
                        put("content", if (j.encrypted) CryptoVault.decrypt(j.content) else j.content)
                        put("mood", j.mood)
                        put("aiReflection", j.aiReflection)
                    })
                }
            })
            put("documents", JSONArray().apply {
                documents.forEach { d ->
                    put(JSONObject().apply {
                        put("title", d.title)
                        put("docType", d.docType)
                        put("content", d.content)
                    })
                }
            })
            put("favoritePlaces", JSONArray().apply {
                places.forEach { p ->
                    put(JSONObject().apply {
                        put("name", p.name)
                        put("address", p.address)
                        put("latitude", p.latitude)
                        put("longitude", p.longitude)
                    })
                }
            })
        }

        file.writeText(root.toString(2))
        return file
    }

    fun getShareUri(context: Context, file: File): Uri =
        FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)

    fun shareFile(context: Context, file: File, mimeType: String, title: String) {
        val uri = getShareUri(context, file)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, title)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(intent, title).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }

    fun shareText(context: Context, text: String, subject: String) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, subject)
            putExtra(Intent.EXTRA_TEXT, text)
        }
        context.startActivity(Intent.createChooser(intent, subject).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }
}
